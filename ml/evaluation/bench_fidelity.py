"""Dysfluency perception fidelity (task M12, second axis).

Latency is only half of the Moshi-vs-cascade comparison. The other half is
whether each path *perceives* dysfluency at all, because that is the entire
premise of this product: a coach that does not notice a block cannot respond
to one appropriately.

The two paths perceive very differently, and the asymmetry is the finding:

  - **Cascade** has an explicit perception stage. M4's wav2vec2 classifier
    emits typed, timed events against a frozen schema
    (`docs/ACOUSTIC_TAG_SCHEMA.md`), so its perception can be scored directly
    against SEP-28k's human labels — precision, recall, F1, per class.

  - **Moshi** has no such stage and exposes no dysfluency output. It consumes
    audio tokens end to end. There is nothing to score against ground truth,
    which is not a measurement failure — it is the architectural fact M12
    exists to document.

So this script measures the cascade's perception against human labels on the
**held-out test split** (never training data), and records Moshi's structural
inability to produce a comparable signal. Reporting a number for one and an
explanation for the other is the honest form of this comparison; inventing a
proxy metric for Moshi would be worse than reporting none.

    python ml/evaluation/bench_fidelity.py --limit 300

Writes `results/fidelity.json` and `results/fidelity.md`.
"""

from __future__ import annotations

import argparse
import json
import sys
import wave
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / "ml" / "dysfluency" / "scripts"))
sys.path.insert(0, str(REPO / "ml" / "dysfluency"))

from sep28k_manifest import (  # noqa: E402
    LABEL_COLUMNS,
    binarize,
    load_labels,
    passes_quality_filter,
    split_episodes,
)

SEP_SRC = REPO / "ml" / "dysfluency" / "sep28k-src"
CLIPS = REPO / "data" / "sep28k" / "audio" / "clips"
CHECKPOINT = REPO / "ml" / "dysfluency" / "checkpoints" / "wav2vec2-dysfluency"

# The classifier emits schema names; SEP-28k's columns are its own. One table,
# in the same order as LABEL_COLUMNS, keeps the two aligned.
SCHEMA_NAMES = [
    "block",
    "prolongation",
    "sound_repetition",
    "word_repetition",
    "interjection",
]


def read_wav_16k(path: Path) -> np.ndarray | None:
    try:
        with wave.open(str(path), "rb") as wf:
            if wf.getnchannels() != 1:
                return None
            frames = wf.readframes(wf.getnframes())
        return np.frombuffer(frames, dtype="<i2").astype(np.float32) / 32768.0
    except Exception:
        return None


def prf(tp: int, fp: int, fn: int) -> tuple[float, float, float]:
    p = tp / (tp + fp) if (tp + fp) else 0.0
    r = tp / (tp + fn) if (tp + fn) else 0.0
    f = 2 * p * r / (p + r) if (p + r) else 0.0
    return p, r, f


def write_report(stats: dict, args, path: Path) -> None:
    per = stats["per_class"]
    lines = [
        "# M12 — Dysfluency Perception Fidelity",
        "",
        "*Generated by `ml/evaluation/bench_fidelity.py`. "
        f"Held-out SEP-28k test split, {stats['n_clips']} clips, "
        f"decision threshold {args.threshold}.*",
        "",
        "The second axis of the Moshi-vs-cascade comparison. Latency says how",
        "*fast* each path answers; this says whether either path actually",
        "**perceives** the dysfluency it is supposed to be responding to.",
        "",
        "## Cascade — scored against human labels",
        "",
        "The cascade has an explicit perception stage (M4's wav2vec2 classifier),",
        "so its output is directly comparable to SEP-28k's human annotations.",
        "These clips are from the held-out test split — never seen in training.",
        "",
        "| Event | Precision | Recall | F1 | Support |",
        "|---|---|---|---|---|",
    ]
    for name in SCHEMA_NAMES:
        s = per[name]
        lines.append(
            f"| {name} | {s['precision']:.3f} | {s['recall']:.3f} "
            f"| {s['f1']:.3f} | {s['support']} |"
        )
    lines += [
        f"| **macro** | **{stats['macro']['precision']:.3f}** "
        f"| **{stats['macro']['recall']:.3f}** "
        f"| **{stats['macro']['f1']:.3f}** | {stats['n_clips']} |",
        "",
        "## Moshi — no comparable signal exists",
        "",
        "Moshi cannot be scored on this axis, and that is the finding rather than",
        "a gap in the measurement:",
        "",
        "- It consumes and emits **audio tokens end to end**. There is no",
        "  intermediate representation of *what kind of dysfluency occurred and",
        "  when* to compare against a human label.",
        "- Its only text output is the Inner Monologue (A4), which is an ASR-like",
        "  transcript of words — not typed, timed dysfluency events.",
        "- Whatever it perceives about delivery is entangled in the generated",
        "  audio and cannot be isolated without a separate perception model —",
        "  which would be measuring that model, not Moshi.",
        "",
        "Fabricating a proxy score here (e.g. running the cascade's own classifier",
        "over Moshi's output audio) would measure the classifier twice and tell us",
        "nothing about Moshi. No number is the honest result.",
        "",
        "## What this means for the architecture",
        "",
        "This is the clearest evidence for the plan's dual-mode design. The",
        "dysfluency timeline (A16) — the demo centerpiece and the feature that",
        "makes the product's novelty visible — **can only be built from the",
        "cascade's perception stage.** Moshi supplies conversational immediacy;",
        "it structurally cannot supply the analysis the coaching depends on.",
        "",
        "Neither path subsumes the other, which is why the product ships both.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=300,
                    help="Max held-out clips to score (CPU inference is slow)")
    ap.add_argument("--threshold", type=float, default=0.5)
    ap.add_argument("--seed", type=int, default=42,
                    help="Must match prepare_splits.py so the test split is "
                         "the same one the classifier never trained on")
    ap.add_argument("--out-dir", default=str(HERE / "results"))
    args = ap.parse_args()

    labels_csv = SEP_SRC / "SEP-28k_labels.subset4.csv"
    if not labels_csv.exists():
        labels_csv = SEP_SRC / "SEP-28k_labels.csv"
    print(f"Labels: {labels_csv.name}")

    clips = [c for c in load_labels(labels_csv, CLIPS) if passes_quality_filter(c)]
    # Same seed as prepare_splits.py's default, and the same episode-level
    # split function, so "test" here is the split M4 never trained on.
    test = split_episodes(clips, seed=args.seed)["test"]
    print(f"Held-out test clips: {len(test)}")

    from inference import DysfluencyClassifier  # noqa: E402

    clf = DysfluencyClassifier(CHECKPOINT, device="cpu")

    tp = {n: 0 for n in SCHEMA_NAMES}
    fp = {n: 0 for n in SCHEMA_NAMES}
    fn = {n: 0 for n in SCHEMA_NAMES}
    support = {n: 0 for n in SCHEMA_NAMES}

    scored = 0
    for clip in test:
        if scored >= args.limit:
            break
        audio = read_wav_16k(Path(clip.clip_path))
        if audio is None or audio.size == 0:
            continue

        truth = binarize(clip)
        # predict() keys by SEP-28k column name ("Block", "SoundRep", ...); the
        # report uses schema names. LABEL_COLUMNS[i] and SCHEMA_NAMES[i] are the
        # same event by construction — see the table where SCHEMA_NAMES is set.
        probs = clf.predict(audio, 16000)

        for i, name in enumerate(SCHEMA_NAMES):
            gold = bool(truth[i])
            pred = float(probs[LABEL_COLUMNS[i]]) >= args.threshold
            support[name] += int(gold)
            if pred and gold:
                tp[name] += 1
            elif pred and not gold:
                fp[name] += 1
            elif gold and not pred:
                fn[name] += 1

        scored += 1
        if scored % 25 == 0:
            print(f"  {scored} clips…", flush=True)

    per = {}
    for name in SCHEMA_NAMES:
        p, r, f = prf(tp[name], fp[name], fn[name])
        per[name] = {
            "precision": p, "recall": r, "f1": f,
            "support": support[name],
            "tp": tp[name], "fp": fp[name], "fn": fn[name],
        }

    macro = {
        k: sum(per[n][k] for n in SCHEMA_NAMES) / len(SCHEMA_NAMES)
        for k in ("precision", "recall", "f1")
    }
    stats = {
        "n_clips": scored,
        "threshold": args.threshold,
        "seed": args.seed,
        "per_class": per,
        "macro": macro,
        "moshi": {
            "scorable": False,
            "reason": "No intermediate dysfluency representation; audio tokens "
                      "end to end. Only text output is the Inner Monologue "
                      "transcript, which carries words, not typed timed events.",
        },
    }

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "fidelity.json").write_text(json.dumps(stats, indent=2), encoding="utf-8")
    write_report(stats, args, out_dir / "fidelity.md")

    print(f"\n  macro F1 {macro['f1']:.3f} over {scored} held-out clips")
    print(f"  wrote {out_dir / 'fidelity.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
